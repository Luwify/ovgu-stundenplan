// Bundles the release notes (changelog/<version>.<lang>.md, the same files the Android releases use) and NOTICE into
// src/generated/changelog.ts for the web's version overview and licenses. Unreleased notes are left out.
import { readFileSync, readdirSync, writeFileSync, mkdirSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const here = dirname(fileURLToPath(import.meta.url))
const root = join(here, '../..')
const dir = join(root, 'changelog')
const cmp = (a, b) => { const x = a.split('.').map(Number); const y = b.split('.').map(Number); for (let i = 0; i < 3; i++) if (x[i] !== y[i]) return y[i] - x[i]; return 0 }
const versions = [...new Set(readdirSync(dir).map((f) => /^(\d+\.\d+\.\d+)\.(de|en)\.md$/.exec(f)?.[1]).filter(Boolean))].sort(cmp)
const read = (v, l) => { try { return readFileSync(join(dir, `${v}.${l}.md`), 'utf8').trim() } catch { return '' } }
const out = versions.map((v) => ({ version: v, de: read(v, 'de'), en: read(v, 'en') || read(v, 'de') }))
const notice = readFileSync(join(root, 'NOTICE'), 'utf8')
mkdirSync(join(here, '../src/generated'), { recursive: true })
writeFileSync(
  join(here, '../src/generated/changelog.ts'),
  '// Generated by scripts/changelog.mjs from changelog/*.md and NOTICE. Do not edit.\n' +
    `export const releases: { version: string; de: string; en: string }[] = ${JSON.stringify(out, null, 1)}\n` +
    `export const notice = ${JSON.stringify(notice)}\n`,
)
console.log(`changelog: ${out.length} versions`)
