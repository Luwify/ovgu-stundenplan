// Copies the strings the web app shares with the Android app from app/src/main/res/values{,-de}/strings.xml into
// src/generated/strings.ts, so wording stays in sync. Android placeholders (%1$s, %1$d, %%) become {1}, {1}, %.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const here = dirname(fileURLToPath(import.meta.url))
const res = join(here, '../../app/src/main/res')
// Every string of the app except the parts the web doesn't have (APK updater, Mensa MD banner, APK sharing).
const SKIP = /^(update_|companion_|mensa_|unknown_sources_|check_|app_share_|auto_check|version_install|version_needs_android|settings_update_badge)/

function unescape(s) {
  return s
    .replace(/<[^>]+>/g, '')
    .replace(/\\n/g, '\n').replace(/\\'/g, "'").replace(/\\"/g, '"').replace(/\\@/g, '@').replace(/\\\?/g, '?')
    .replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"').replace(/&apos;/g, "'").replace(/&amp;/g, '&')
    .replace(/%(\d+)\$[sd]/g, '{$1}').replace(/(?<!%)%[sd]/g, '{1}').replace(/%%/g, '%')
}

function read(dir) {
  const xml = readFileSync(join(res, dir, 'strings.xml'), 'utf8')
  const out = {}
  for (const m of xml.matchAll(/<string name="([a-z0-9_]+)"[^>]*>([\s\S]*?)<\/string>/g)) out[m[1]] = unescape(m[2])
  for (const m of xml.matchAll(/<plurals name="([a-z0-9_]+)"[^>]*>([\s\S]*?)<\/plurals>/g)) {
    const forms = {}
    for (const i of m[2].matchAll(/<item quantity="(\w+)">([\s\S]*?)<\/item>/g)) forms[i[1]] = unescape(i[2])
    out[m[1]] = forms
  }
  return out
}

const en = read('values')
const de = read('values-de')
const KEYS = Object.keys(en).filter((k) => !SKIP.test(k))
const pick = (all, lang) => Object.fromEntries(KEYS.map((k) => {
  if (!(k in all)) {
    if (lang === 'de' && k in en) return [k, en[k]]
    throw new Error(`missing string ${k} (${lang})`)
  }
  return [k, all[k]]
}))
mkdirSync(join(here, '../src/generated'), { recursive: true })
writeFileSync(
  join(here, '../src/generated/strings.ts'),
  '// Generated by scripts/strings.mjs from the Android app\'s strings.xml. Do not edit.\n' +
    `export const appStrings = ${JSON.stringify({ en: pick(en, 'en'), de: pick(de, 'de') }, null, 1)} as const\n`,
)
console.log(`strings: ${KEYS.length} keys`)
