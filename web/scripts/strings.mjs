function unescape(s) {
  return s
    .replace(/<[^>]+>/g, '')
    .replace(/\\n/g, '\n').replace(/\\'/g, "'").replace(/\\"/g, '"').replace(/\\@/g, '@').replace(/\\\?/g, '?')
    .replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"').replace(/&apos;/g, "'").replace(/&amp;/g, '&')
    .replace(/%(\d+)\$[sd]/g, '{$1}').replace(/%%/g, '%')
}

function read(dir) {
  const xml = readFileSync(join(res, dir, 'strings.xml'), 'utf8')
  const out = {}
  for (const m of xml.matchAll(/<string name="([a-z0-9_]+)"[^>]*>([\s\S]*?)<\/string>/g)) out[m[1]] = unescape(m[2])
  for (const m of xml.matchAll(/<plurals name="([a-z0-9_]+)"[^>]*>([\s\S]*?)<\/plurals>/g)) {
    const forms = {}
    for (const i of m[2].matchAll(/<item quantity="(\w+)">([\s\S]*?)<\/item>/g)) forms[i[1]] = unescape(i[2])
    out[m[1]] = forms
  }
  return out
}

const en = read('values')
const de = read('values-de')
const pick = (all, lang) => Object.fromEntries(KEYS.map((k) => {
  if (!(k in all)) {
    if (lang === 'de' && k in en) return [k, en[k]]
    throw new Error(`missing string ${k} (${lang})`)
  }
  return [k, all[k]]
}))
mkdirSync(join(here, '../src/generated'), { recursive: true })
writeFileSync(
  join(here, '../src/generated/strings.ts'),
  '// Generated by scripts/strings.mjs from the Android app\'s strings.xml. Do not edit.\n' +
    `export const appStrings = ${JSON.stringify({ en: pick(en, 'en'), de: pick(de, 'de') }, null, 1)} as const\n`,
)
console.log(`strings: ${KEYS.length} keys`)
