package de.luwify.stundenplanmd.core

import de.luwify.stundenplanmd.core.compat.CompatProbe
import java.io.File

/**
 * Build tool (task `compatGolden`, run before the JS tests): writes what the JVM build of :core produces for the
 * fixture ([CompatProbe.describe]) as a Kotlin source for jsTest, which must reproduce it exactly.
 */
fun main(args: Array<String>) {
    val ics = File(args[0]).readText()
    val lines = CompatProbe.describe(ics)
    val out = File(args[1]).apply { parentFile.mkdirs() }
    fun lit(s: String) = "\"" + CompatProbe.b64(s.encodeToByteArray()) + "\""
    out.writeText(
        buildString {
            appendLine("// Generated by :core:compatGolden from the JVM build. Do not edit.")
            appendLine("package de.luwify.stundenplanmd.core.compat")
            appendLine()
            appendLine("object CompatGolden {")
            appendLine("    val ics: String = CompatProbe.unb64(${lit(ics)}).decodeToString()")
            appendLine("    val values: List<Pair<String, String>> = listOf(")
            for ((k, v) in lines) appendLine("        \"$k\" to CompatProbe.unb64(${lit(v)}).decodeToString(),")
            appendLine("    )")
            appendLine("}")
        },
    )
    println("compatGolden: ${lines.size} values -> $out")
}
